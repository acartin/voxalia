-- Declarative dialplan flow catalog.
-- Voxalia stores safe, provider-neutral actions. The Asterisk provisioner later
-- renders these actions into concrete Asterisk dialplan applications.

create table if not exists asterisk.dialplan_action_catalog (
  id bigint generated by default as identity primary key,
  action_key text not null unique,
  label text not null,
  description text not null default '',
  category text not null,
  requires_target boolean not null default false,
  parameter_schema jsonb not null default '{}'::jsonb,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dialplan_action_catalog_category_ck check (category in ('call_control', 'recording', 'routing', 'policy', 'workflow', 'system')),
  constraint dialplan_action_catalog_status_ck check (status in ('active', 'inactive'))
);

create table if not exists asterisk.context_action_rules (
  id bigint generated by default as identity primary key,
  context_key text not null,
  action_key text not null references asterisk.dialplan_action_catalog(action_key) on delete cascade,
  allowed boolean not null default true,
  default_enabled boolean not null default false,
  sort_order integer not null default 100,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint context_action_rules_context_key_ck check (context_key in ('inbound', 'internal', 'outbound', 'queue', 'after_hours', 'emergency', 'recording', 'test')),
  constraint context_action_rules_sort_order_ck check (sort_order >= 0),
  unique (context_key, action_key)
);

create table if not exists asterisk.dialplan_flows (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  dial_context_id bigint not null,
  flow_key text not null,
  display_name text not null,
  entry_extension text not null default 's',
  status text not null default 'active',
  version integer not null default 1,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dialplan_flows_status_ck check (status in ('active', 'inactive', 'draft')),
  constraint dialplan_flows_version_ck check (version > 0),
  constraint dialplan_flows_context_fk foreign key (dial_context_id, tenant_id)
    references asterisk.dial_contexts(id, tenant_id) on delete cascade,
  unique (id, tenant_id),
  unique (tenant_id, dial_context_id, flow_key, version)
);

create table if not exists asterisk.dialplan_steps (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  dialplan_flow_id bigint not null,
  step_order integer not null,
  action_key text not null references asterisk.dialplan_action_catalog(action_key) on delete restrict,
  label text not null default '',
  parameters jsonb not null default '{}'::jsonb,
  on_success_step_order integer,
  on_failure_step_order integer,
  status text not null default 'active',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dialplan_steps_step_order_ck check (step_order > 0),
  constraint dialplan_steps_status_ck check (status in ('active', 'inactive', 'draft')),
  constraint dialplan_steps_flow_fk foreign key (dialplan_flow_id, tenant_id)
    references asterisk.dialplan_flows(id, tenant_id) on delete cascade,
  unique (dialplan_flow_id, step_order)
);

create index if not exists dialplan_action_catalog_category_idx
  on asterisk.dialplan_action_catalog(category, status);

create index if not exists context_action_rules_context_idx
  on asterisk.context_action_rules(context_key, allowed, sort_order);

create index if not exists dialplan_flows_context_idx
  on asterisk.dialplan_flows(tenant_id, dial_context_id, status);

create index if not exists dialplan_steps_flow_idx
  on asterisk.dialplan_steps(tenant_id, dialplan_flow_id, step_order);

drop trigger if exists dialplan_action_catalog_set_updated_at on asterisk.dialplan_action_catalog;
create trigger dialplan_action_catalog_set_updated_at
before update on asterisk.dialplan_action_catalog
for each row execute function asterisk.set_updated_at();

drop trigger if exists context_action_rules_set_updated_at on asterisk.context_action_rules;
create trigger context_action_rules_set_updated_at
before update on asterisk.context_action_rules
for each row execute function asterisk.set_updated_at();

drop trigger if exists dialplan_flows_set_updated_at on asterisk.dialplan_flows;
create trigger dialplan_flows_set_updated_at
before update on asterisk.dialplan_flows
for each row execute function asterisk.set_updated_at();

drop trigger if exists dialplan_steps_set_updated_at on asterisk.dialplan_steps;
create trigger dialplan_steps_set_updated_at
before update on asterisk.dialplan_steps
for each row execute function asterisk.set_updated_at();

