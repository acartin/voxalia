with tenant_row as (
  select id as tenant_id from public.tenants where tenant_key = 'hotel-valle-azul'
),
flow_seed as (
  select
    dc.tenant_id,
    dc.id as dial_context_id,
    seed.flow_key,
    seed.display_name,
    seed.entry_extension,
    seed.metadata
  from asterisk.dial_contexts dc
  join tenant_row t on t.tenant_id = dc.tenant_id
  join (
    values
      ('inbound', 'main-inbound', 'Main inbound flow', 's', '{"purpose":"did-entry"}'::jsonb),
      ('after_hours', 'after-hours-message', 'After-hours message flow', 's', '{"purpose":"closed-hours"}'::jsonb),
