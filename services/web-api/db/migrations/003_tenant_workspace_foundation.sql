  method_type text not null,
  label text not null default '',
  value text not null,
  is_primary boolean not null default false,
  can_receive_escalations boolean not null default false,
  availability text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_contact_methods_type_ck check (method_type in ('phone', 'email', 'sms', 'whatsapp', 'extension')),
  constraint tenant_contact_methods_contact_tenant_fk foreign key (contact_id, tenant_id)
    references public.tenant_contacts(id, tenant_id) on delete cascade,
