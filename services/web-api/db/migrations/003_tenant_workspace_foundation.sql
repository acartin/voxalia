);

create table if not exists public.agent_profiles (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.auth_users(id) on delete cascade,
  display_name text not null,
  languages text[] not null default array['en']::text[],
  skills text[] not null default array[]::text[],
  status text not null default 'offline',
  supervisor_user_id bigint references public.auth_users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint agent_profiles_status_ck check (status in ('offline', 'available', 'ringing', 'on_call', 'after_call_work', 'break', 'training', 'unavailable')),
  unique (id, user_id),
  unique (user_id)
);

create table if not exists public.tenant_agent_assignments (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  agent_profile_id bigint not null references public.agent_profiles(id) on delete cascade,
  assignment_type text not null default 'primary',
  queue_key text not null default '',
  priority integer not null default 100,
  status text not null default 'active',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_agent_assignments_type_ck check (assignment_type in ('primary', 'backup', 'supervisor', 'specialist')),
  constraint tenant_agent_assignments_status_ck check (status in ('active', 'inactive')),
  constraint tenant_agent_assignments_priority_ck check (priority >= 0),
  unique (id, tenant_id),
  unique (tenant_id, agent_profile_id, assignment_type, queue_key)
);

create table if not exists public.tenant_scripts (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  channel_id bigint,
  service_policy_id bigint,
  script_key text not null,
  script_type text not null,
  title text not null,
  language text not null default 'en',
  body text not null,
  status text not null default 'draft',
  version integer not null default 1,
  effective_from timestamptz,
  effective_to timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_scripts_type_ck check (script_type in ('greeting', 'intake', 'escalation', 'after_hours', 'disclosure', 'faq', 'handoff', 'other')),
  constraint tenant_scripts_status_ck check (status in ('draft', 'active', 'retired')),
  constraint tenant_scripts_version_ck check (version > 0),
  constraint tenant_scripts_effective_window_ck check (effective_to is null or effective_from is null or effective_to > effective_from),
  constraint tenant_scripts_channel_tenant_fk foreign key (channel_id, tenant_id)
    references public.tenant_channels(id, tenant_id),
  constraint tenant_scripts_policy_tenant_fk foreign key (service_policy_id, tenant_id)
    references public.tenant_service_policies(id, tenant_id),
  unique (id, tenant_id),
  unique (tenant_id, script_key, language, version)
);

