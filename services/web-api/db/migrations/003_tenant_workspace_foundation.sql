insert into public.tenant_product_subscriptions (tenant_id, product_key, display_name, status, activated_at, config)
select id, 'managed-reception', 'Managed Reception', 'active', now(), '{"phase":"foundation"}'::jsonb
from public.tenants
where tenant_key = 'voxalia'
on conflict (tenant_id, product_key) do update set
  display_name = excluded.display_name,
  status = excluded.status,
  config = excluded.config,
  updated_at = now();

