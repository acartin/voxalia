-- Voxalia tenant workspace foundation.
-- Idempotent by design: safe to run repeatedly in phase 0 environments.

create table if not exists public.tenant_product_subscriptions (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  product_key text not null,
  display_name text not null,
  status text not null default 'active',
  activated_at timestamptz,
  cancelled_at timestamptz,
  config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_product_subscriptions_status_ck check (status in ('active', 'trial', 'paused', 'cancelled')),
  constraint tenant_product_subscriptions_product_key_ck check (product_key in ('managed-reception', 'multichannel-inbox', 'call-intelligence', 'agent-assist', 'automated-chat', 'sales-followup')),
  constraint tenant_product_subscriptions_active_dates_ck check (cancelled_at is null or activated_at is null or cancelled_at >= activated_at),
  unique (id, tenant_id),
  unique (tenant_id, product_key)
);

create table if not exists public.tenant_service_policies (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  policy_key text not null,
  display_name text not null,
  status text not null default 'active',
  default_language text not null default 'en',
  supported_languages text[] not null default array['en']::text[],
  after_hours_behavior text not null default 'take_message',
  callback_window text,
  recording_disclosure text not null default '',
  recording_retention_days integer not null default 365,
  escalation_notes text not null default '',
  agent_notes text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_service_policies_status_ck check (status in ('active', 'inactive', 'draft')),
  constraint tenant_service_policies_after_hours_behavior_ck check (after_hours_behavior in ('take_message', 'callback_next_business_day', 'emergency_only', 'transfer_to_partner', 'closed_message')),
  constraint tenant_service_policies_recording_retention_days_ck check (recording_retention_days > 0),
  unique (id, tenant_id),
  unique (tenant_id, policy_key)
);

create table if not exists public.tenant_service_hours (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  service_policy_id bigint references public.tenant_service_policies(id) on delete cascade,
  weekday smallint not null,
  starts_at time,
  ends_at time,
  is_closed boolean not null default false,
  label text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_service_hours_weekday_ck check (weekday between 0 and 6),
  constraint tenant_service_hours_window_ck check (
    (is_closed and starts_at is null and ends_at is null)
    or (not is_closed and starts_at is not null and ends_at is not null and starts_at < ends_at)
  ),
  constraint tenant_service_hours_policy_tenant_fk foreign key (service_policy_id, tenant_id)
    references public.tenant_service_policies(id, tenant_id) on delete cascade
);

create table if not exists public.tenant_channels (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  service_policy_id bigint,
  channel_key text not null,
  channel_type text not null,
  display_name text not null,
  provider text not null default 'voxalia',
  routing_key text not null default '',
  default_language text not null default 'en',
  status text not null default 'active',
  recording_required boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_channels_type_ck check (channel_type in ('voice_toll_free', 'voice_local', 'chatwoot_inbox', 'voxalia_webchat', 'meta_whatsapp', 'email')),
  constraint tenant_channels_status_ck check (status in ('active', 'inactive', 'provisioning', 'failed')),
  constraint tenant_channels_policy_tenant_fk foreign key (service_policy_id, tenant_id)
    references public.tenant_service_policies(id, tenant_id),
  unique (id, tenant_id),
  unique (tenant_id, channel_key),
  unique (tenant_id, channel_type, routing_key)
);

